//! The incremental visible-window flatten must equal the full merge
//! (Task 148.6, issue #559).
//!
//! `Buffer::visible_as_tchars_and_tags` keeps a merge cache and, on the hot
//! per-frame path, re-merges only the rows from the first changed one onward.
//! `Buffer::visible_as_tchars_and_tags_full_merge` rebuilds everything from
//! the per-row caches and is the oracle. The buffer checks the two against
//! each other with a `debug_assert!`, which is compiled out of release
//! builds, so these tests compare them explicitly and hold in either build.
//!
//! Two layers:
//!
//! - replays of the two minimised `terminal_state` fuzz reproducers, one per
//!   distinct cause found for #559; and
//! - a deterministic property test that drives generated byte streams (OSC 8
//!   hyperlinks, wrapped and partial auto-detected URLs, SGR, wide and
//!   combining characters, wraps, cursor moves, partial-row edits, scrolling,
//!   the alternate screen) through the whole emulator and compares the two
//!   flattens after random steps, so several edits accumulate between
//!   flattens as they do between GUI frames.

use freminal_terminal_emulator::interface::TerminalEmulator;

/// Byte 0 is the column seed (`1 + b % 300` = 40 columns), byte 1 the row
/// seed (`1 + b % 120` = 10 rows), byte 2 the chunk seed, the rest the
/// stream. Committed as
/// `fuzz/regressions/terminal_state/flatten-incremental-clean-wrapped-url-group-below-rebuilt-row`.
///
/// A clean soft-wrapped auto-detected URL sits below a row that is edited
/// afterwards. The incremental merge restarts at the edited row, so the group
/// must be redetected there; it used to be skipped and came out truncated
/// (`https://h=` instead of `https://h==`).
const CLEAN_GROUP_BELOW_REBUILT_ROW: &[u8] = &[
    0x27, 0x09, 0x01, 0x18, 0x66, 0x69, 0x6c, 0x65, 0x3a, 0x2f, 0x0a, 0x37, 0x3b, 0x68, 0x74, 0x74,
    0x70, 0x73, 0x3a, 0x2f, 0x2f, 0x65, 0x78, 0x61, 0x6d, 0x70, 0x6c, 0x65, 0x2e, 0x63, 0xb8, 0x20,
    0x0a, 0x1b, 0x33, 0x79, 0x07, 0x6e, 0x33, 0x79, 0x07, 0x68, 0x74, 0x74, 0x70, 0x73, 0x3a, 0x2f,
    0x2f, 0x68, 0x3d, 0x3d, 0xb8, 0x1b, 0x5b, 0x48, 0x78, 0x20, 0x0a, 0x5b, 0x3a, 0x2f, 0x33,
];

/// 20 columns, 3 rows, chunk seed 6. Committed as
/// `fuzz/regressions/terminal_state/flatten-incremental-stale-url-before-rebuilt-continuation-row`.
///
/// Row 1 ends in `m` and its continuation row 2 reads `ailto:http:/`, so the
/// pair is the URL `mailto:http:/` (the partial scheme at the end of row 2
/// is the group's only URL signal). Appending `?` to row 2 removes that
/// signal; the clean row 1 must lose its URL tag too, but the incremental
/// merge reused it from the previous merge.
const STALE_URL_BEFORE_REBUILT_CONTINUATION_ROW: &[u8] = &[
    0x13, 0x02, 0x06, 0x68, 0x65, 0x61, 0x64, 0x0d, 0x0a, 0x61, 0x62, 0x63, 0x64, 0x65, 0x66, 0x67,
    0x68, 0x69, 0x6a, 0x6b, 0x6c, 0x6d, 0x6e, 0x6f, 0x70, 0x71, 0x72, 0x73, 0x6d, 0x61, 0x69, 0x6c,
    0x74, 0x6f, 0x3a, 0x68, 0x74, 0x74, 0x70, 0x3a, 0x2f, 0x3f,
];

/// Mirrors `freminal_fuzz::split_chunks(seed, 4, data)`: the fuzz target
/// feeds the stream in LCG-sized chunks and snapshots every fourth chunk.
fn split_chunks(seed: u8, data: &[u8]) -> Vec<&[u8]> {
    let max_len = (1 + usize::from(seed >> 2)).saturating_mul(4);
    let mut state = u32::from(seed);
    let mut rest = data;
    let mut chunks = Vec::new();
    while !rest.is_empty() {
        state = state.wrapping_mul(1_664_525).wrapping_add(1_013_904_223);
        let draw = usize::try_from(state >> 16).unwrap_or(0);
        let len = (1 + draw % max_len).min(rest.len());
        let (head, tail) = rest.split_at(len);
        chunks.push(head);
        rest = tail;
    }
    chunks
}

/// Feed `bytes` to a fresh headless emulator of the given size.
fn headless(cols: usize, rows: usize) -> TerminalEmulator {
    let (mut emulator, _write_rx) = TerminalEmulator::new_headless(None);
    assert!(
        emulator.set_win_size(cols, rows, 8, 16).is_ok(),
        "resize to {cols}x{rows} must succeed"
    );
    emulator
}

/// Flatten the visible window through the incremental path and through the
/// full merge, and assert they are identical.
fn assert_flattens_agree(emulator: &mut TerminalEmulator, context: &str) {
    let buffer = emulator.internal.handler.buffer_mut();
    let incremental = buffer.visible_as_tchars_and_tags(0);
    let full = buffer.visible_as_tchars_and_tags_full_merge(0);
    assert_eq!(
        incremental, full,
        "{context}: incremental flatten diverged from the full merge"
    );
}

/// Replay a `terminal_state` fuzz input the way the fuzz target does, with an
/// explicit oracle comparison at every point it builds a snapshot.
fn replay_fuzz_input(data: &[u8]) {
    let [cols_byte, rows_byte, seed, stream @ ..] = data else {
        panic!("reproducer is shorter than its three header bytes");
    };
    let cols = 1 + usize::from(*cols_byte) % 300;
    let rows = 1 + usize::from(*rows_byte) % 120;
    let mut emulator = headless(cols, rows);

    let chunks = split_chunks(*seed, stream);
    let last = chunks.len().saturating_sub(1);
    for (index, chunk) in chunks.into_iter().enumerate() {
        emulator.handle_incoming_data(chunk);
        emulator.internal.window_commands.clear();
        if index % 4 == 3 || index == last {
            assert_flattens_agree(&mut emulator, &format!("chunk {index}"));
        }
    }
}

#[test]
fn clean_wrapped_url_group_below_rebuilt_row_matches_full_merge() {
    replay_fuzz_input(CLEAN_GROUP_BELOW_REBUILT_ROW);
}

#[test]
fn stale_url_before_rebuilt_continuation_row_matches_full_merge() {
    replay_fuzz_input(STALE_URL_BEFORE_REBUILT_CONTINUATION_ROW);
}

/// Deterministic xorshift64*: the property test must reproduce from its seed
/// alone, with no dependence on a global RNG or the clock.
struct Rng(u64);

impl Rng {
    const fn new(seed: u64) -> Self {
        // Never zero, or xorshift sticks there.
        Self(seed.wrapping_mul(0x9E37_79B9_7F4A_7C15) | 1)
    }

    const fn next_u64(&mut self) -> u64 {
        self.0 ^= self.0 >> 12;
        self.0 ^= self.0 << 25;
        self.0 ^= self.0 >> 27;
        self.0.wrapping_mul(0x2545_F491_4F6C_DD1D)
    }

    /// A value in `0..bound` (`bound` must be non-zero).
    fn below(&mut self, bound: usize) -> usize {
        let bound = u64::try_from(bound).unwrap_or(u64::MAX).max(1);
        usize::try_from(self.next_u64() % bound).unwrap_or(0)
    }

    fn pick<'a, T>(&mut self, items: &'a [T]) -> &'a T {
        // `items` is never empty at any call site below.
        &items[self.below(items.len())]
    }
}


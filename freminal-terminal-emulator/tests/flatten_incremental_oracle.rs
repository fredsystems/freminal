/// One generated step: a few fragments, mostly text, some control sequences.
fn generate_step(rng: &mut Rng) -> Vec<u8> {
    let mut out = String::new();
    for _ in 0..=rng.below(4) {
        if rng.below(10) < 6 {
            out.push_str(rng.pick(WORDS));
        } else {
            out.push_str(rng.pick(CONTROLS));
        }
    }
    out.into_bytes()
}

/// Sizes small enough that URLs and words wrap constantly, plus a normal one.
const SIZES: &[(usize, usize)] = &[(8, 4), (10, 3), (13, 6), (20, 5), (32, 8), (80, 24)];

const SEEDS: u64 = 100;
const STEPS: usize = 250;

#[test]
fn incremental_flatten_matches_full_merge_over_generated_streams() {
    for seed in 0..SEEDS {
        let mut rng = Rng::new(seed);
        let (cols, rows) = *rng.pick(SIZES);
        let mut emulator = headless(cols, rows);

        for step in 0..STEPS {
            let bytes = generate_step(&mut rng);
            emulator.handle_incoming_data(&bytes);
            emulator.internal.window_commands.clear();

            // Skip some flattens so several edits accumulate between them,
            // as they do between GUI frames, and flatten twice in a row
            // sometimes so the no-op path is covered too.
            if rng.below(4) != 0 {
                let context = format!(
                    "seed {seed} ({cols}x{rows}) step {step}, last input {:?}",
                    String::from_utf8_lossy(&bytes)
                );
                assert_flattens_agree(&mut emulator, &context);
                if rng.below(4) == 0 {
                    assert_flattens_agree(&mut emulator, &context);
                }
            }
        }
    }
}
